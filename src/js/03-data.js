// Строка вида «5 тем, 25 вопросов, финал» для карточек и лобби.
function stats(p) {
  const th = p.rounds.reduce((a, r) => a + r.themes.length, 0),
    q = p.rounds.reduce((a, r) => a + r.themes.reduce((b, t) => b + t.questions.length, 0), 0);
  return `${p.rounds.length > 1 ? p.rounds.length + " раунда · " : ""}${th} ${plural(th, "тема", "темы", "тем")}, ${q} ${plural(q, "вопрос", "вопроса", "вопросов")}${p.final ? ", финал" : ""}`;
}

